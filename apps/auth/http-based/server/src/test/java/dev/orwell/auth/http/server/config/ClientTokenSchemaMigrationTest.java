package dev.orwell.auth.http.server.config;

import dev.orwell.auth.http.server.config.ClientTokenSchemaMigration.ClientTokenMigrationRunner;
import dev.orwell.logging.Logger;
import dev.orwell.testing.PostgresJdbcTest;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.SQLException;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Drives the migration against a real Postgres for the same reason
 * {@link WorkspaceSchemaMigrationTest} does: {@code NOT NULL} on a populated table and the catalog
 * queries that find the column are both database behaviour.
 */
class ClientTokenSchemaMigrationTest extends PostgresJdbcTest {

    private final Logger logger = entry -> {
    };

    @BeforeEach
    void dropEverything() throws SQLException {
        execute("DROP TABLE IF EXISTS client_tokens", "DROP TABLE IF EXISTS client_identities");
    }

    /** The reason a plain {@code ddl-auto: update} cannot do this: the table already has rows. */
    @Test
    void makesTheColumnNotNullOnAPopulatedTable() throws SQLException {
        givenLegacySchemaWithAToken();

        migrate();

        assertEquals(List.of("NO"), query("""
                SELECT is_nullable FROM information_schema.columns
                WHERE table_name = 'client_tokens' AND column_name = 'last_used_at'
                """));
    }

    /**
     * The point of migrating rather than defaulting to {@code created_at}: a token issued long ago
     * and used continuously since has no usage record to inherit, so it is given a fresh clock and
     * a full idle period to prove itself in. Backfilling {@code created_at} would have the first
     * sweep after an upgrade delete it.
     */
    @Test
    void backfillsExistingTokensToNowRatherThanToWhenTheyWereIssued() throws SQLException {
        givenLegacySchemaWithAToken();

        migrate();

        assertEquals(List.of("t"), query("SELECT last_used_at > created_at FROM client_tokens"));
        assertEquals(List.of("t"), query("SELECT last_used_at > now() - interval '1 minute' FROM client_tokens"));
    }

    @Test
    void createsTheIndexTheCleanupJobScansOn() throws SQLException {
        givenLegacySchemaWithAToken();

        migrate();

        assertTrue(query("SELECT indexname FROM pg_indexes WHERE tablename = 'client_tokens'")
                .contains("idx_client_tokens_identity_created"));
    }

    @Test
    void doesNothingWhenThereIsNoTableYet() {
        migrate();

        assertEquals(List.of(), query("""
                SELECT table_name FROM information_schema.tables WHERE table_name = 'client_tokens'
                """));
    }

    /** Running twice must be as harmless as running once — it runs on every startup. */
    @Test
    void isSafeToRunAgain() throws SQLException {
        givenLegacySchemaWithAToken();

        migrate();
        List<String> afterFirstRun = query("SELECT last_used_at FROM client_tokens");
        migrate();

        assertEquals(afterFirstRun, query("SELECT last_used_at FROM client_tokens"),
                "a second run must not re-stamp a token that already carries a usage record");
    }

    /** The tables as Hibernate created them before tokens tracked their use. */
    private void givenLegacySchemaWithAToken() throws SQLException {
        execute("""
                CREATE TABLE client_identities (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    workspace VARCHAR(64) NOT NULL,
                    client_id VARCHAR(128) NOT NULL,
                    secret_hash VARCHAR(512) NOT NULL,
                    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                    active BOOLEAN NOT NULL
                )
                """,
                """
                CREATE TABLE client_tokens (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    client_identity_id BIGINT NOT NULL REFERENCES client_identities (id),
                    token_hash VARCHAR(128) NOT NULL UNIQUE,
                    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
                )
                """,
                """
                INSERT INTO client_identities (workspace, client_id, secret_hash, created_at, active)
                VALUES ('def', 'client-a', 'hash', now() - interval '400 days', true)
                """,
                """
                INSERT INTO client_tokens (client_identity_id, token_hash, created_at)
                SELECT id, 'token-hash', now() - interval '400 days' FROM client_identities
                """);
    }

    private void migrate() {
        new ClientTokenMigrationRunner(dataSource(), logger).migrate();
    }
}
